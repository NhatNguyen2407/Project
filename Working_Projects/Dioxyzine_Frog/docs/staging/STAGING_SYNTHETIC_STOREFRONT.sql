begin;

create table public.products (
  id text primary key check (id like 'STG-%'),
  title text not null,
  description text,
  category text,
  type text not null,
  moq integer default 1,
  pricing_type text default 'contact',
  price numeric default 0,
  stock integer default 0,
  rating numeric default 5.0,
  image_cover text,
  images_gallery text,
  created_at timestamptz default now(),
  sold integer default 0,
  cut_style text
);

create table public.vouchers (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code like 'STG-%'),
  discount_type text not null,
  discount_value numeric not null,
  usage_limit integer,
  used_count integer default 0,
  expires_at timestamptz,
  is_active boolean default true,
  created_at timestamptz default now()
);

create table public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'customer'
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  user_id uuid references auth.users(id),
  customer_name text not null,
  customer_email text not null check (customer_email like '%@example.invalid'),
  phone_number text,
  shipping_address text,
  total_amount numeric not null,
  payment_method text default 'synthetic' check (payment_method = 'synthetic'),
  payment_status text default 'pending',
  transaction_id text check (transaction_id is null or transaction_id like 'STG-%'),
  tracking_code text,
  order_status text default 'processing',
  cart_items jsonb not null,
  rating integer,
  review_comment text,
  admin_reply text,
  is_hidden boolean not null default false
);

create table public.wishlists (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id),
  product_id text not null references public.products(id),
  created_at timestamptz default now()
);

create table public.stock_reservations (
  id uuid primary key default gen_random_uuid(),
  paypal_order_id text not null check (paypal_order_id like 'STG-%'),
  product_id text not null references public.products(id),
  quantity integer not null check (quantity > 0),
  expires_at timestamptz not null,
  status text not null default 'active'
    check (status in ('active','consumed','released')),
  created_at timestamptz not null default now()
);

create table public.order_reviews (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id),
  user_id uuid not null references auth.users(id),
  product_ids text[] not null default '{}',
  product_names text[] not null default '{}',
  customer_name text,
  rating integer not null check (rating between 1 and 5),
  review_comment text,
  admin_reply text,
  is_hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Default-deny all seven new public tables; no admin writes or real service calls.
alter table public.products enable row level security;
alter table public.vouchers enable row level security;
alter table public.user_roles enable row level security;
alter table public.orders enable row level security;
alter table public.wishlists enable row level security;
alter table public.stock_reservations enable row level security;
alter table public.order_reviews enable row level security;

revoke all on table public.products, public.vouchers, public.user_roles,
  public.orders, public.wishlists, public.stock_reservations,
  public.order_reviews from public, anon, authenticated;

